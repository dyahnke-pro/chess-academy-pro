import { useEffect, useState } from 'react';
import { Navigate } from 'react-router-dom';
import { LessonPlayer } from './LessonPlayer';
import { generatedLessonFor } from '../../services/generatedLesson';
import type { LessonScript, OpeningRecord } from '../../types';

interface GeneratedWatchProps {
  opening: OpeningRecord;
  /** The variation tab being watched, or null for the main line. */
  variationIndex: number | null;
  onExit: () => void;
  onComplete: () => void;
  onContinueToNext: () => void;
}

/** THE WATCH RUNG FOR AN OPENING BUILT FROM THE GAMES (WO-ALL-OPENINGS-01 P3).
 *  The line the page shows is generated by the pipeline Learn with Coach uses
 *  and played by the masterclass `LessonPlayer`, on the page — so finishing it
 *  ticks the Watch rung and opens Learn, Practice and Play. When it cannot be
 *  built, the coach teaches it live as before. */
export function GeneratedWatch({ opening, variationIndex, onExit, onComplete, onContinueToNext }: GeneratedWatchProps): JSX.Element {
  const variation = variationIndex !== null ? opening.variations?.[variationIndex] : undefined;
  const name = variation?.name ?? opening.name;
  const pgn = variation?.pgn ?? opening.pgn;
  const [state, setState] = useState<{ status: 'loading' } | { status: 'ready'; script: LessonScript } | { status: 'failed' }>({ status: 'loading' });

  useEffect(() => {
    let live = true;
    const moves = pgn.trim().split(/\s+/).filter(Boolean);
    void generatedLessonFor({ name, eco: opening.eco, moves, openingId: opening.id, color: opening.color, corpusNotes: true })
      .then((script) => { if (live) setState(script ? { status: 'ready', script } : { status: 'failed' }); });
    return () => { live = false; };
  }, [name, pgn, opening.eco, opening.id, opening.color]);

  if (state.status === 'failed') {
    const params = new URLSearchParams({ teach: name, auto: '1', oid: opening.id });
    if (opening.eco) params.set('eco', opening.eco);
    return <Navigate to={`/coach/teach?${params.toString()}`} replace />;
  }
  if (state.status === 'loading') {
    return (
      <div className="flex flex-1 items-center justify-center p-6" data-testid="generated-watch-loading">
        <p className="text-sm text-theme-text-muted">Building the lesson from the games…</p>
      </div>
    );
  }
  return (
    <LessonPlayer
      script={state.script}
      onExit={onExit}
      onComplete={onComplete}
      onContinueToNext={onContinueToNext}
    />
  );
}
